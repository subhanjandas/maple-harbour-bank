import{test,expect}from'@playwright/test';
import{writeFileSync,mkdirSync}from'node:fs';
import {execFileSync} from 'node:child_process';
const out='../docs/assets';
test('customer payment → operations return → published analytics → actual lineage',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Alex Morgan',exact:false}).click();
 await expect(page.getByRole('heading',{name:'Welcome back, Alex.'})).toBeVisible();
 await expect(page.getByText('Harbour Savings',{exact:true}).first()).toBeVisible();
 await page.getByLabel('Amount (CAD)',{exact:true}).fill('125.00');
 await page.getByRole('button',{name:'Post simulated payment'}).click();
 await expect(page.getByRole('status')).toContainText('Payment posted successfully');
 await expect(page.getByRole('region',{name:'Payment trace'})).toBeVisible();
 mkdirSync(out,{recursive:true});await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/customer-overview.png',fullPage:false});await page.screenshot({path:out+'/customer-light.png',fullPage:true});
 await page.getByRole('button',{name:'Switch to Dusk theme'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/customer-dusk.png',fullPage:true});
 await page.getByRole('button',{name:'Switch to light theme'}).click();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Taylor Reid',exact:false}).click();
 await page.locator('.payment-row').first().click();
 await page.getByRole('button',{name:'Acknowledge settlement'}).click();
 await expect(page.getByText('PARTIALLY RETURNED',{exact:true})).toHaveCount(0);
 await page.getByLabel('Partial return amount (CAD)',{exact:true}).fill('30.00');
 await page.getByRole('button',{name:'Post return installment'}).click();
 await expect(page.locator('.trace-summary')).toContainText('PARTIALLY_RETURNED');
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/operations.png',fullPage:true});
 await expect.poll(async()=>{await page.getByRole('button',{name:'Refresh trace',exact:true}).click();return page.locator('table').last().innerText();},{timeout:20000}).not.toContain('Not published');
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Jordan Martin',exact:false}).click();
 await expect(page.getByRole('heading',{name:'Activity, with its evidence attached.'})).toBeVisible();
 await expect(page.getByText('Reconciled',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/analytics.png',fullPage:true});
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Casey Roy',exact:false}).click();
 await expect(page.getByRole('heading',{name:'Trust comes from what you can inspect.'})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/control-room.png',fullPage:true});
 await page.getByRole('button',{name:'Architecture & flow',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Follow the flow.'})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/architecture.png',fullPage:true});
 await expect(page.locator('a[href*="banking-model-atlas"]')).not.toHaveCount(0);
 expect(errors).toEqual([]);
 writeFileSync(out+'/provenance.json',JSON.stringify({source_commit:process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD']).toString().trim(),capture_time:new Date().toISOString(),environment:'GitHub Actions ephemeral PostgreSQL + API + worker',note:'Actual browser screenshots, not mockups. Synthetic scenario.'},null,2));
 const video=page.video();await page.close();if(video)await video.saveAs(out+'/payment-demo.webm');
});
test('mobile navigation, theme persistence and architecture accessibility',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/?page=architecture&node=outbox');
 await expect(page.getByRole('heading',{name:'Transactional outbox',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Switch to Dusk theme'}).click();await page.reload();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByText('Accessible component and connection directory').click();
 await expect(page.getByRole('table').first()).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:out+'/mobile-dusk.png',fullPage:true});
});
